package main

import (
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// newGenDocsCmd writes the CLI reference page of the documentation site
// from the command tree itself, so it can't drift from the code. The docs
// build runs it; it's hidden from help.
func newGenDocsCmd() *cobra.Command {
	return &cobra.Command{
		Use:    "gen-docs FILE",
		Short:  "Write the CLI reference page for the documentation site",
		Hidden: true,
		Args: func(cmd *cobra.Command, args []string) error {
			if len(args) != 1 {
				return fmt.Errorf("gen-docs takes the output file")
			}
			return nil
		},
		RunE: func(cmd *cobra.Command, args []string) error {
			f, err := os.Create(args[0])
			if err != nil {
				return err
			}
			if err := writeCLIDocs(f, cmd.Root()); err != nil {
				f.Close()
				return err
			}
			return f.Close()
		},
	}
}

// writeCLIDocs writes one Markdown page: the global flags once, then a
// section per command (depth first, in cobra's order), each with its usage,
// description and own flags.
func writeCLIDocs(w io.Writer, root *cobra.Command) error {
	var b strings.Builder
	b.WriteString("# CLI reference\n\n")
	b.WriteString("<!-- Generated by `careen gen-docs` from the command tree; edit the commands' help text, not this page. -->\n\n")
	b.WriteString("Every command, generated from careen's own help text. ")
	b.WriteString("Run `careen COMMAND --help` for the same information in a terminal.\n\n")

	b.WriteString("## Global flags\n\n")
	b.WriteString("These work with every command.\n\n")
	writeFlags(&b, root.PersistentFlags())

	for _, c := range documented(root) {
		writeCommand(&b, c)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// documented is every command below root worth a section, depth first.
func documented(root *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		for _, sub := range c.Commands() {
			if sub.Hidden || sub.Name() == "help" || sub.Name() == "completion" {
				continue
			}
			out = append(out, sub)
			walk(sub)
		}
	}
	walk(root)
	return out
}

func writeCommand(b *strings.Builder, c *cobra.Command) {
	fmt.Fprintf(b, "## %s\n\n", c.CommandPath())
	fmt.Fprintf(b, "%s.\n\n", escape(strings.TrimSuffix(c.Short, ".")))

	b.WriteString("```text\n")
	if c.Runnable() {
		fmt.Fprintf(b, "%s\n", c.UseLine())
	}
	if c.HasAvailableSubCommands() {
		fmt.Fprintf(b, "%s COMMAND\n", c.CommandPath())
	}
	b.WriteString("```\n\n")

	if c.Long != "" {
		writeLong(b, c.Long)
	}

	if subs := visibleSubcommands(c); len(subs) > 0 {
		b.WriteString("Subcommands:\n\n")
		for _, s := range subs {
			fmt.Fprintf(b, "- [`%s`](#%s): %s\n", s.CommandPath(), anchor(s.CommandPath()), escape(s.Short))
		}
		b.WriteString("\n")
	}

	writeFlags(b, c.LocalNonPersistentFlags())
}

func visibleSubcommands(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, s := range c.Commands() {
		if !s.Hidden && s.Name() != "help" && s.Name() != "completion" {
			out = append(out, s)
		}
	}
	return out
}

// writeLong turns help text into Markdown: paragraphs stay text, and
// blocks indented by two spaces (examples, tables of states) become code
// blocks, as they read in a terminal.
func writeLong(b *strings.Builder, long string) {
	for _, para := range strings.Split(strings.TrimSpace(long), "\n\n") {
		lines := strings.Split(para, "\n")
		indented := true
		for _, l := range lines {
			if !strings.HasPrefix(l, "  ") {
				indented = false
				break
			}
		}
		if indented {
			b.WriteString("```text\n")
			for _, l := range lines {
				b.WriteString(strings.TrimPrefix(l, "  ") + "\n")
			}
			b.WriteString("```\n\n")
			continue
		}
		b.WriteString(escape(strings.Join(lines, " ")) + "\n\n")
	}
}

// escape keeps placeholders like <secretsDir> from being read as HTML.
func escape(s string) string {
	return strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(s)
}

// writeFlags writes a table of fs's flags, help excluded.
func writeFlags(b *strings.Builder, fs *pflag.FlagSet) {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "`--" + f.Name
		switch t := f.Value.Type(); {
		case t == "bool":
		case f.NoOptDefVal != "": // --reboot alone means --reboot=policy
			name += "[=" + flagArg(t) + "]"
		default:
			name += " " + flagArg(t)
		}
		name += "`"
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		def := ""
		switch f.DefValue {
		case "", "false", "0", "[]", "0s":
		default:
			def = "`" + f.DefValue + "`"
		}
		rows = append(rows, fmt.Sprintf("| %s | %s | %s |", name, def, strings.ReplaceAll(escape(f.Usage), "|", `\|`)))
	})
	if len(rows) == 0 {
		return
	}
	b.WriteString("| Flag | Default | Description |\n| --- | --- | --- |\n")
	b.WriteString(strings.Join(rows, "\n") + "\n\n")
}

// flagArg names a flag's argument the way the help shows it.
func flagArg(typ string) string {
	switch typ {
	case "stringSlice":
		return "LIST"
	case "stringArray": // repeatable
		return "VALUE"
	case "duration":
		return "DURATION"
	case "int":
		return "N"
	default:
		return strings.ToUpper(typ)
	}
}

// anchor is the heading id MkDocs gives "## careen vm plan".
func anchor(heading string) string {
	return strings.ReplaceAll(strings.ToLower(heading), " ", "-")
}
